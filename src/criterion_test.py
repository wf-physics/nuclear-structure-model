# -*- coding: utf-8 -*-
"""
v4.0 法则二·下限（β⁻ 电子逃逸判据）的原样实现与验证集测试
判据（A 类，积分到无穷远）:
    W_β(n) = 1.44 * [ 1/a + Σ_i 1/|r_pi - r_n| ]   (MeV), 源 = N_Z 原有质子 + 1 新生质子
    W_β < Q_β⁻ → 判"β⁻ 衰变";  W_β ≥ Q_β⁻ → 判"稳定"
验证集核素（几何取示意构型，键长在 0.8–2.2 fm 约束内）:
    自由中子 / ³H / ⁶He / ¹⁴C —— 四个实验上均真实发生 β⁻ 衰变的核素
"""
import numpy as np

def W_beta(proton_distances, a):
    """v4.0 §2.2.3：N+1 个质子源的标量库仑势叠加（MeV）"""
    return 1.44 * (1.0 / a + sum(1.0 / d for d in proton_distances))

def verdict(W, Q):
    return "β⁻ 衰变" if W < Q else "稳定（判据关闭通道）"

CASES = [
    # (名称, 中子到各质子距离 fm, Q_β⁻ MeV, 实验事实, 示意几何说明)
    ("自由中子", [], 0.782343, "衰变, τ=879.4 s", "无原有质子源，仅新生质子自项"),
    ("³H (1p2n)", [1.7], 0.018591, "衰变, t½=12.32 y", "三角形边长 1.7 fm，中子到唯一质子"),
    ("⁶He (2p4n)", [1.78, 1.78], 3.5078, "衰变, t½=0.807 s", "两质子相距 1.9 fm，中子在腰位"),
    ("¹⁴C (6p8n)", [2.5]*6, 0.156476, "衰变, t½=5730 y", "示意：中子到 6 个质子平均 2.5 fm"),
]

def main():
    print("=" * 92)
    print("v4.0 法则二·下限判据验证集测试（A 类积分路径）")
    print("=" * 92)
    for a in (0.8, 0.9, 1.0):
        print(f"\n--- 软化半径 a = {a} fm ---")
        print(f"{'核素':<14}{'W_β (MeV)':>12}{'Q_β⁻ (MeV)':>13}{'判据输出':>16}"
              f"{'实验事实':>18}{'判定':>6}")
        for name, dists, Q, exp, _ in CASES:
            W = W_beta(dists, a)
            v = verdict(W, Q)
            ok = "✗" if ("衰变" in exp) != ("衰变" in v) else "✓"
            print(f"{name:<14}{W:>12.3f}{Q:>13.4f}{v:>16}{exp:>22}{ok:>4}")

    print("\n--- 对照：若删除自项 1/a（仅保留结构项）---")
    print(f"{'核素':<14}{'W_结构 (MeV)':>14}{'Q_β⁻ (MeV)':>13}{'判据输出':>16}"
          f"{'实验事实':>18}{'判定':>6}")
    for name, dists, Q, exp, _ in CASES:
        W = 1.44 * sum(1.0 / d for d in dists) if dists else 0.0
        v = verdict(W, Q)
        ok = "✗" if ("衰变" in exp) != ("衰变" in v) else "✓"
        print(f"{name:<14}{W:>14.3f}{Q:>13.4f}{v:>16}{exp:>22}{ok:>4}")

    print("""
结论摘要：
1. 含自项时，W_β ≥ 1.44/a ≥ 1.44 MeV 是全核素共同背景，
   自由中子 W=1.44/a > Q=0.782 → v4.0 判"自由中子稳定"，与模型自身锚点矛盾（P0 缺陷）。
2. 所有 Q_β⁻ < 1.44 MeV 的核素（³H、¹⁴C 等）一律被判"稳定"，判据失去分辨力。
3. 判据的实际分辨能力来自 W 与 Q 的相对大小，而 W 中几何结构项是 O(1) 量级修正，
   自项是 O(1.4–1.8 MeV) 的常数背景 → 构型信息被淹没。
""")

if __name__ == "__main__":
    main()
